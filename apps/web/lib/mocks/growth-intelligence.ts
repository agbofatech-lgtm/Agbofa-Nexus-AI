function opportunity(
  input: Omit<
    GrowthOpportunityRecord,
    | keyof GrowthMeta
    | "evidence"
    | "expectedImpact"
    | "estimatedCost"
    | "confidence"
    | "provenance"
  > & { confidenceScore: number; impactValue: number; costValue: number },
): GrowthOpportunityRecord {
  const { confidenceScore, impactValue, costValue, ...rest } = input;
  return {
    ...meta(
      confidenceScore,
      `Agreement across ${rest.evidenceIds.length} simulated evidence signals`,
    ),
    ...rest,
    evidence: refs(rest.evidenceIds),
    expectedImpact: impact(impactValue),
    estimatedCost: cost(costValue),
  };
}
